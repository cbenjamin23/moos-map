from __future__ import annotations

import math
import os
import tempfile
from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path

from .errors import ValidationError
from .models import Bounds, Origin


INFO_KEYS = {
    "lat_north",
    "lat_south",
    "lon_east",
    "lon_west",
    "datum_lat",
    "datum_lon",
}
EXPORT_ID_PREFIX = "moos_map_export_id = "
MISSION_LONGITUDE_PREFIX = "moos_map_mission_longitude = "
TIFF_BINDING_PREFIX = "moos-map placement v1:"
MOOS_SNIPPET_HEADER = "// Generated by moos-map"


def tiff_binding(
    export_id: str, bounds: Bounds, origin: Origin, *, viewer_longitude: float | None = None
) -> str:
    coordinates = (
        bounds.west, bounds.south, bounds.east, bounds.north, origin.latitude, origin.longitude,
        origin.longitude if viewer_longitude is None else viewer_longitude,
    )
    values = ",".join(f"{value:.10f}" for value in coordinates).replace(
        "-0.0000000000", "0.0000000000"
    )
    digest = sha256(values.encode("ascii")).hexdigest()
    return f"{TIFF_BINDING_PREFIX}{export_id}:{digest}"


@dataclass(frozen=True, slots=True)
class InfoData:
    bounds: Bounds
    origin: Origin
    comments: tuple[str, ...]
    viewer_longitude: float

    def as_dict(self) -> dict[str, object]:
        return {
            "bounds": self.bounds.as_dict(),
            "origin": self.origin.as_dict(),
            "comments": list(self.comments),
        }


def _write_text_atomic(destination: Path, content: str) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.", dir=destination.parent, text=True
    )
    temporary_path = Path(temporary_name)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_path, destination)
    finally:
        temporary_path.unlink(missing_ok=True)


def write_info_file(
    destination: Path,
    *,
    actual_bounds: Bounds,
    origin: Origin,
    source_id: str,
    source_attribution: str,
    zoom: int,
    requested_bounds: Bounds,
    generator_version: str,
    export_id: str | None = None,
) -> None:
    viewer_longitude = actual_bounds.longitude_near_center(origin.longitude)
    lines = [
        f"// generated_by = moos-map {generator_version}",
        f"// source = {source_id}",
        f"// attribution = {source_attribution}",
        f"// zoom = {zoom}",
        (
            "// requested_bounds_wsen = "
            f"{requested_bounds.west:.10f},{requested_bounds.south:.10f},"
            f"{requested_bounds.east:.10f},{requested_bounds.north:.10f}"
        ),
        "",
        f"lat_north = {actual_bounds.north:.10f}",
        f"lat_south = {actual_bounds.south:.10f}",
        f"lon_east  = {actual_bounds.east:.10f}",
        f"lon_west  = {actual_bounds.west:.10f}",
        f"datum_lat = {origin.latitude:.10f}",
        f"datum_lon = {viewer_longitude:.10f}",
        "",
    ]
    if export_id:
        lines.insert(1, f"// {EXPORT_ID_PREFIX}{export_id}")
    if viewer_longitude != origin.longitude:
        lines.insert(1, f"// {MISSION_LONGITUDE_PREFIX}{origin.longitude:.10f}")
    _write_text_atomic(destination, "\n".join(lines))


def parse_info_file(path: Path) -> InfoData:
    try:
        if not path.is_file():
            raise ValidationError(f"Missing MOOS info file: {path}")
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise ValidationError(f"Missing MOOS info file: {path}") from exc
    except UnicodeDecodeError as exc:
        raise ValidationError(f"Invalid UTF-8 in MOOS info file: {path}") from exc
    except OSError as exc:
        reason = exc.strerror or str(exc)
        raise ValidationError(f"Cannot read MOOS info file {path}: {reason}") from exc

    values: dict[str, float] = {}
    comments: list[str] = []
    for line_number, original in enumerate(text.splitlines(), 1):
        stripped = original.strip()
        if stripped.startswith("//"):
            comments.append(stripped[2:].strip())
            continue
        content = original.split("//", 1)[0].strip()
        if not content:
            continue
        if content.count("=") != 1:
            raise ValidationError(
                f"Invalid .info syntax at line {line_number}: {original}"
            )
        key, raw_value = (part.strip() for part in content.split("=", 1))
        if key not in INFO_KEYS:
            raise ValidationError(
                f"Unsupported .info key '{key}' at line {line_number}; "
                "pMarineViewer rejects unknown keys"
            )
        if key in values:
            raise ValidationError(f"Duplicate .info key '{key}' at line {line_number}")
        try:
            values[key] = float(raw_value)
        except ValueError as exc:
            raise ValidationError(
                f"Non-numeric .info value for '{key}' at line {line_number}"
            ) from exc

    missing = INFO_KEYS.difference(values)
    if missing:
        raise ValidationError(f"Missing .info keys: {', '.join(sorted(missing))}")

    bounds = Bounds(
        west=values["lon_west"], south=values["lat_south"],
        east=values["lon_east"], north=values["lat_north"],
    )
    viewer_longitude = values["datum_lon"]
    mission_longitudes = [comment.removeprefix(MISSION_LONGITUDE_PREFIX) for comment in comments
                          if comment.startswith(MISSION_LONGITUDE_PREFIX)]
    longitude = viewer_longitude
    if mission_longitudes:
        try:
            if len(mission_longitudes) != 1:
                raise ValueError("duplicate mission longitude")
            longitude = float(mission_longitudes[0])
        except ValueError as exc:
            raise ValidationError("Invalid mission longitude in .info metadata") from exc
        if not math.isclose(
            bounds.longitude_near_center(longitude), viewer_longitude, rel_tol=0, abs_tol=1e-9
        ):
            raise ValidationError("The .info viewer datum and mission longitude disagree")
    origin = Origin(latitude=values["datum_lat"], longitude=longitude)
    return InfoData(bounds, origin, tuple(comments), viewer_longitude)


def moos_snippet_text(*, tiff_name: str, origin: Origin) -> str:
    return "\n".join(
        [
            MOOS_SNIPPET_HEADER,
            "// Keep the same-basename .tif and .info files together.",
            "// Copy them into the mission directory or add this map folder to",
            "// IVP_IMAGE_DIRS so pMarineViewer can find them.",
            "",
            "// Global mission geodesy:",
            f"LatOrigin  = {origin.latitude:.10f}",
            f"LongOrigin = {origin.longitude:.10f}",
            "",
            "// Add this inside ProcessConfig = pMarineViewer:",
            f"tiff_file = {tiff_name}",
            "",
        ]
    )


def write_moos_snippet(
    destination: Path,
    *,
    tiff_name: str,
    origin: Origin,
) -> None:
    content = moos_snippet_text(tiff_name=tiff_name, origin=origin)
    _write_text_atomic(destination, content)
